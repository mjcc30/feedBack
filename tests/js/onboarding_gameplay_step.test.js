// The Gameplay Settings controls moved OUT of the note_detect calibration
// wizard into the onboarding overlay (profile.js step 8), right after the
// song-directory step: first-run parcours = name/avatar -> song directory ->
// gameplay settings -> Feats opt-in -> instrument paths (+ input setup, whose
// calibration wizard auto-launches) -> [amp sims on desktop] -> challenge.
//
// Source contracts are checked on static/v3/profile.js (LF-normalized — the
// worktree checks out CRLF on Windows).

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const PROFILE_JS = path.join(__dirname, '..', '..', 'static', 'v3', 'profile.js');

function readProfile() {
    return fs.readFileSync(PROFILE_JS, 'utf8').replace(/\r\n/g, '\n');
}

test('step 8 (gameplay settings) sits between the song directory and the Feats opt-in', () => {
    const src = readProfile();
    assert.ok(src.includes('id="v3-ob-step8"'), 'the step-8 block exists in the onboarding DOM');
    const i2 = src.indexOf('id="v3-ob-step2"');
    const i8 = src.indexOf('id="v3-ob-step8"');
    const i3 = src.indexOf('id="v3-ob-step3"');
    assert.ok(i2 !== -1 && i8 !== -1 && i3 !== -1);
    assert.ok(i2 < i8 && i8 < i3, 'DOM order: song directory (2) -> gameplay settings (8) -> Feats opt-in (3)');
});

test('the step sequence visits gameplay settings right after the song directory', () => {
    const src = readProfile();
    assert.ok(src.includes('let stepSeq = [1, 2, 8, 3, 4];'), 'initial sequence');
    assert.ok(src.includes('stepSeq = [1, 2, 8, 3, 4];'), 'sequence rebuilt by the step-4 handler');
    // The desktop-only amp-sim step and the challenge still append after it.
    assert.ok(src.includes('if (isDesktop) stepSeq.push(5);'));
    assert.ok(src.includes('stepSeq.push(7);'));
});

test('setStep covers steps 1..8 and labels the gameplay-settings step', () => {
    const src = readProfile();
    assert.ok(src.includes('for (let i = 1; i <= 8; i++) {'), 'step blocks 1..8 are toggled');
    assert.ok(src.includes("n === 8 ? 'Gameplay settings'"), 'subtitle for the gameplay step');
    assert.ok(src.includes("submit.textContent = n === 7 ? 'Play it now' : 'Next';"),
        'step 8 keeps the Next label (only the challenge says Play it now)');
    assert.ok(src.includes("skipBtn.classList.toggle('hidden', !(n === 2 || n === 7));"),
        'skip stays on the song-directory and challenge steps only');
});

test('step 2 (Next and Skip) and step 8 advance through the sequence', () => {
    const src = readProfile();
    assert.equal((src.match(/setStep\(nextStepAfter\(2\)\);/g) || []).length, 2,
        'step-2 Next and Skip both follow the sequence (to gameplay settings)');
    assert.equal((src.match(/setStep\(nextStepAfter\(8\)\);/g) || []).length, 1,
        'step-8 Next continues to the Feats opt-in');
    assert.ok(src.includes('if (step === 8) {'), 'the step-8 submit handler exists');
});

test('the ten gameplay controls write through the Settings globals', () => {
    const src = readProfile();
    for (const wiring of [
        'window.highway.setLefty(el.checked)',
        'window.setMastery(el.value)',
        'window.setAvOffsetMs(el.value)',
        'window.setCountdownBeforeSong(el.checked)',
        'window.setShowUpNext(el.checked)',
        'window.setAutoplayExit(el.checked)',
        'window.setConfirmExitSong(el.checked)',
        "window.persistSetting('default_arrangement', el.value)",
        "window.persistSetting('miss_penalty', el.value)",
        "window.persistSetting('fail_behavior', el.value)",
    ]) {
        assert.ok(src.includes(wiring), 'control wiring missing: ' + wiring);
    }
});

test('controls are seeded from localStorage and a one-shot /api/settings fetch', () => {
    const src = readProfile();
    assert.ok(src.includes("fetch('/api/settings')"), 'one-shot GET to pre-fill the controls');
    for (const key of ['master_difficulty', 'av_offset_ms', 'default_arrangement', 'miss_penalty', 'fail_behavior']) {
        assert.ok(src.includes('s.' + key), 'pre-fill reads ' + key);
    }
    for (const ls of ['lefty', 'countdownBeforeSong', 'showUpNext', 'autoplayExit', 'confirmExitSong']) {
        assert.ok(src.includes("'" + ls + "'"), 'seed reads localStorage ' + ls);
    }
    // All ten control ids are generated by the helpers and wired by name.
    for (const cls of ['lefty', 'mastery', 'avoffset', 'countdown', 'upnext', 'autoplay',
        'confirmexit', 'arrangement', 'misspenalty', 'failbehavior']) {
        const built = src.includes("gpToggle('" + cls + "'") || src.includes("gpSlider('" + cls + "'")
            || src.includes("gpSelect('" + cls + "'");
        assert.ok(built, 'control built: ' + cls);
        assert.ok(src.includes("gpOn('" + cls + "'") || src.includes("gpOnInput('" + cls + "'"),
            'control wired: ' + cls);
    }
});

test('the input-setup step auto-launches the calibration wizard during onboarding', () => {
    const src = readProfile();
    assert.ok(src.includes('payload: { instruments, autoCalibrate: true }'),
        'the input-calibration run command asks for autoCalibrate');
    assert.ok(src.includes('launch(instruments, { autoCalibrate: true })'),
        'the no-capabilities fallback auto-calibrates too');
});
